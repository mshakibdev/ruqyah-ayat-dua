BN = '০১২৩৪৫৬৭৮৯'
bn = lambda n: ''.join(BN[int(c)] for c in str(n))


def build(key, stem, title, short):
    rows = json.loads((HERE / 'draft' / (stem + '.json')).read_text())
    items, n = [], 0

    def add(ch, o):
        nonlocal n
        n += 1
        it = dict(ch=ch, num=bn(n), title=o['title'], cnt=o.get('cnt', ''), ar=o['ar'])
        for f in ('tr', 'mn', 'niyat', 'src'):
            if o.get(f): it[f] = o[f]
        items.append(it)

    n = 0
    for o in OPEN:
        add('এক · শুরু করার দোয়া', o)

    # সমাপ্তির তিন কুল = ইখলাস/ফালাক/নাসের *শেষ* উপস্থিতি।
    # (কিছু নথিতে একই সূরা আয়াত অংশেও আছে — সেটি যেন সরে না যায়।)
    last = {}
    for i, r in enumerate(rows):
        if r['surah'] in CLOSE_Q and r['first'] == 1:
            last[r['surah']] = i
    cut = set(last.values())
    ay = [r for i, r in enumerate(rows) if i not in cut]
    cq = [rows[i] for i in sorted(cut)]

    for r in ay:
        add('দুই · আয়াতসমূহ', dict(
            title=f"সূরা {r['surah_name'].replace('  ', ' ')} : {bn(r['first'])}"
                  + (f"-{bn(r['last'])}" if r['last'] != r['first'] else ''),
            cnt=r['cnt'], ar=[r['ar']], mn=r['mn'], niyat=r.get('niyat', '')))

    n = 0
    for o in SPECIAL[key]:
        add('তিন · বিশেষ দোয়া', o)

    n = 0
    for r in sorted(cq, key=lambda x: x['surah']):
        c, ni = CLOSE_Q[r['surah']]
        add('চার · সমাপ্তির সূরা ও দোয়া', dict(
            title=f"সূরা {r['surah_name']} : {bn(r['first'])}-{bn(r['last'])}",
            cnt=c, ar=[r['ar']], mn=r['mn'], niyat=ni))
    for o in CLOSE_DUA:
        add('চার · সমাপ্তির সূরা ও দোয়া', o)

    data = dict(title=title, short=short,
                source='রুকইয়াহ প্রোটোকল · রাকী ফয়সাল আহমেদ সাবিত · আল কুরআন রুকইয়াহ হিলিং সেন্টার',
                items=items)
    (OUT / f'{key}.json').write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n')
    print(f'✓ {key}.json — {len(items)} আইটেম '
          f'(শুরু {len(OPEN)} · আয়াত {len(ay)} · বিশেষ {len(SPECIAL[key])} · সমাপ্তি {len(cq)+len(CLOSE_DUA)})')


if __name__ == '__main__':
    for args in COLS:
        build(*args)
